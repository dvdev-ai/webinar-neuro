def no_yo(text: str) -> str:
    return text.replace("ё", "е").replace("Ё", "Е")


def humanize(text: str) -> str:
    t = no_yo(str(text))
    t = t.replace("→", "->")
    t = t.replace(" — ", " - ")
    t = t.replace("—", " - ")
    return t


def cap_first(text: str) -> str:
    t = text.lstrip()
    if not t:
        return text
    return text[: len(text) - len(t)] + t[0].upper() + t[1:]


def _set_run_font(run, size_pt: int, bold: bool = False):
    run.font.name = FONT_NAME
    run.font.size = Pt(size_pt)
    run.font.bold = bold
    run.font.color.rgb = BLACK
    rPr = run._r.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.insert(0, rFonts)
    rFonts.set(qn("w:ascii"), FONT_NAME)
    rFonts.set(qn("w:hAnsi"), FONT_NAME)
    rFonts.set(qn("w:eastAsia"), FONT_NAME)


def _set_spacing_single(para):
    """Одинарный интервал, after=0 — как в правке пользователя."""
    pPr = para._p.get_or_add_pPr()
    spacing = pPr.find(qn("w:spacing"))
    if spacing is None:
        spacing = OxmlElement("w:spacing")
        pPr.append(spacing)
    spacing.set(qn("w:after"), "0")
    spacing.set(qn("w:line"), "240")
    spacing.set(qn("w:lineRule"), "auto")
    # убрать before, если был
    if spacing.get(qn("w:before")) is not None:
        del spacing.attrib[qn("w:before")]


def _set_first_line(para, twips: int | None):
    pPr = para._p.get_or_add_pPr()
    ind = pPr.find(qn("w:ind"))
    if twips is None:
        if ind is not None:
            pPr.remove(ind)
        return
    if ind is None:
        ind = OxmlElement("w:ind")
        pPr.append(ind)
    ind.set(qn("w:firstLine"), str(twips))
    for attr in ("w:left", "w:right", "w:hanging"):
        key = qn(attr)
        if ind.get(key) is not None:
            del ind.attrib[key]


def setup_landscape(doc: Document) -> None:
    for sec in doc.sections:
        sec.orientation = WD_ORIENT.LANDSCAPE
        sec.page_width = Cm(29.7)
        sec.page_height = Cm(21.0)
        sec.top_margin = Cm(1.5)
        sec.bottom_margin = Cm(1.5)
        sec.left_margin = Cm(1.8)
        sec.right_margin = Cm(1.8)


def add_para(
    doc,
    text: str,
    *,
    bold: bool = False,
    size: int = 12,
    align=WD_ALIGN_PARAGRAPH.JUSTIFY,
    red_line: bool = True,
):
    p = doc.add_paragraph()
    p.alignment = align
    _set_spacing_single(p)
    _set_first_line(p, 709 if red_line else None)
    run = p.add_run(humanize(text))
    _set_run_font(run, size, bold=bold)
    return p


def add_title(doc, text: str):
    return add_para(
        doc,
        text,
        bold=True,
        size=14,
        align=WD_ALIGN_PARAGRAPH.CENTER,
        red_line=False,
    )


def add_h(doc, text: str):
    return add_para(doc, text, bold=True, size=12, red_line=True)


def add_p(doc, text: str):
    return add_para(doc, text, bold=False, size=12, red_line=True)


def add_li(doc, text: str):
    return add_para(doc, cap_first(text), bold=False, size=12, red_line=True)


def _cell_clear(cell):
    for p in cell.paragraphs[1:]:
        p._element.getparent().remove(p._element)
    if cell.paragraphs:
        cell.paragraphs[0].clear()


def _cell_text(cell, text, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT, size=10):
    _cell_clear(cell)
    p = cell.paragraphs[0]
    p.alignment = align
    _set_spacing_single(p)
    _set_first_line(p, None)
    run = p.add_run(humanize(text))
    _set_run_font(run, size, bold=bold)
    cell.vertical_alignment = WD_ALIGN_VERTICAL.TOP


def _cell_lines(cell, lines, size=10):
    _cell_clear(cell)
    for i, line in enumerate(lines):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        _set_spacing_single(p)
        _set_first_line(p, None)
        run = p.add_run(humanize(cap_first(line)))
        _set_run_font(run, size, bold=False)
    cell.vertical_alignment = WD_ALIGN_VERTICAL.TOP


def _set_table_full_width(table):
    tbl = table._tbl
    tblPr = tbl.tblPr
    if tblPr is None:
        tblPr = OxmlElement("w:tblPr")
        tbl.insert(0, tblPr)
    tblW = tblPr.find(qn("w:tblW"))
    if tblW is None:
        tblW = OxmlElement("w:tblW")
        tblPr.append(tblW)
    tblW.set(qn("w:w"), "5000")
    tblW.set(qn("w:type"), "pct")


def _set_col_widths(table, widths_cm):
    for row in table.rows:
        for cell, w in zip(row.cells, widths_cm):
            cell.width = Cm(w)


def make_table(doc, headers, rows, col_widths=None, font_size=10):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    _set_table_full_width(table)
    for cell, h in zip(table.rows[0].cells, headers):
        _cell_text(cell, h, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, size=font_size)
    for ri, row_data in enumerate(rows):
        for cell, val in zip(table.rows[ri + 1].cells, row_data):
            if isinstance(val, list):
                _cell_lines(cell, val, size=font_size)
            else:
                _cell_text(cell, val, size=font_size)
    if col_widths:
        _set_col_widths(table, col_widths)
    return table




